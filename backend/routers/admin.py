from fastapi import APIRouter, Depends, HTTPException, Query, status
from typing import Dict, Any, Optional
from pydantic import BaseModel, Field
from backend.database import fetch_all, fetch_one, execute_write
from backend.auth import get_current_admin

router = APIRouter(prefix="/api/admin", tags=["Admin & Analytics"])

class UserStatusUpdate(BaseModel):
    status: str = Field(..., pattern="^(active|suspended)$")

@router.get("/stats")
def get_library_kpis(admin: Dict[str, Any] = Depends(get_current_admin)):
    """
    Computes top-level institutional KPIs for librarian overview.
    Uses aggregate DBMS functions across core normalized tables.
    """
    total_books = fetch_one("SELECT COUNT(*) AS val FROM books")["val"]
    total_copies = fetch_one("SELECT COUNT(*) AS val FROM book_copies")["val"]
    active_loans = fetch_one("SELECT COUNT(*) AS val FROM loans WHERE return_date IS NULL")["val"]
    
    overdue_loans = fetch_one("""
    SELECT COUNT(*) AS val 
    FROM loans 
    WHERE return_date IS NULL AND datetime('now') > datetime(due_date)
    """)["val"]

    unpaid_fines_res = fetch_one("""
    SELECT COALESCE(SUM(amount), 0.0) AS val 
    FROM fines 
    WHERE payment_status = 'unpaid'
    """)["val"]
    unpaid_fines = float(unpaid_fines_res) if unpaid_fines_res else 0.0

    total_students = fetch_one("SELECT COUNT(*) AS val FROM users WHERE role = 'member'")["val"]
    waiting_requests = fetch_one("SELECT COUNT(*) AS val FROM waitlist WHERE status = 'waiting'")["val"]
    room_reservations_today = fetch_one("SELECT COUNT(*) AS val FROM room_bookings WHERE booking_date = date('now') AND status = 'confirmed'")["val"]

    return {
        "total_books": total_books,
        "total_copies": total_copies,
        "active_loans": active_loans,
        "overdue_loans": overdue_loans,
        "unpaid_fines": unpaid_fines,
        "total_students": total_students,
        "waiting_requests": waiting_requests,
        "room_reservations_today": room_reservations_today
    }

@router.get("/audit-logs")
def get_audit_logs(
    target_table: Optional[str] = Query(None, description="Filter by table name: 'fines', 'books', 'book_copies'"),
    admin: Dict[str, Any] = Depends(get_current_admin)
):
    """
    Retrieves real-time audit logs automatically generated by database triggers
    (e.g., trg_fine_waived_audit, trg_book_delete_audit) for tamper-proof accountability.
    """
    if not isinstance(target_table, str):
        target_table = None

    query = """
    SELECT 
        al.log_id,
        al.actor_id,
        u.full_name AS actor_name,
        u.library_card_no AS actor_card,
        al.action_type,
        al.target_table,
        al.target_record_id,
        al.old_value,
        al.new_value,
        al.timestamp
    FROM audit_logs al
    LEFT JOIN users u ON al.actor_id = u.user_id
    WHERE 1=1
    """
    params = []
    if target_table:
        query += " AND al.target_table = %s"
        params.append(target_table)

    query += " ORDER BY al.timestamp DESC, al.log_id DESC LIMIT 100"
    return fetch_all(query, tuple(params))

@router.get("/users")
def list_library_users(admin: Dict[str, Any] = Depends(get_current_admin)):
    """Librarian / Admin: List all library cardholders with their loan statistics."""
    query = """
    SELECT 
        u.user_id,
        u.library_card_no,
        u.full_name,
        u.email,
        u.phone,
        u.role,
        u.status,
        u.created_at,
        (SELECT COUNT(*) FROM loans WHERE user_id = u.user_id AND return_date IS NULL) AS active_loans_count,
        (SELECT COALESCE(SUM(amount), 0) FROM fines WHERE user_id = u.user_id AND payment_status = 'unpaid') AS unpaid_fine_balance
    FROM users u
    ORDER BY u.role ASC, u.full_name ASC
    """
    return fetch_all(query)

@router.patch("/users/{user_id}/status")
def update_user_status(user_id: int, body: UserStatusUpdate, admin: Dict[str, Any] = Depends(get_current_admin)):
    """Suspend or reactivate patron library privileges."""
    user = fetch_one("SELECT user_id, full_name, role FROM users WHERE user_id = %s", (user_id,))
    if not user:
        raise HTTPException(status_code=404, detail="User account not found.")

    if user["role"] == "admin":
        raise HTTPException(status_code=400, detail="Cannot alter administrative status through this endpoint.")

    execute_write("UPDATE users SET status = %s WHERE user_id = %s", (body.status, user_id))
    return {"message": f"Patron '{user['full_name']}' status updated to '{body.status}'."}
